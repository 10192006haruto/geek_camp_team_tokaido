/** 全角・半角、大文字・小文字、記号の違いをそろえる。空白は1つにまとめて区切りとして残す。 */
export function normalizeShopName(name: string): string {
  return name.normalize("NFKC").toLowerCase()
    .replace(/[’‘`´]/g, "'")
    .replace(/[・･]/g, "・")
    .replace(/\s+/g, " ")
    .trim();
}

const SHORT_NAME_LENGTH = 3;
const BOUNDARY = /^[\s(（\[「『【・\-－—_/|｜:：,，.。!！]/;
const NORMALIZED = NATIONAL_CHAIN_NAMES.map(normalizeShopName)
  // 長い名前から照合する（「ステーキガスト」を「ガスト」より先に見る必要はないが、一致理由を安定させる）
  .sort((a, b) => b.length - a.length);

/** 全国チェーンの店名リストに当たれば、そのブランド名（正規化後）を返す。当たらなければ null。 */
export function matchNationalChain(shopName: string, names: readonly string[] = NORMALIZED): string | null {
  const name = normalizeShopName(shopName);
  for (const brand of names) {
    if (!name.startsWith(brand)) continue;
    const rest = name.slice(brand.length);
    if (brand.length > SHORT_NAME_LENGTH || rest === "" || BOUNDARY.test(rest)) return brand;
  }
  return null;
}

export const isNationalChain = (shopName: string) => matchNationalChain(shopName) !== null;
